// Run once:  cd contracts && npm i --no-save @noble/curves @noble/hashes && node script/gen-p256-vectors.mjs > test/utils/P256Vectors.sol
// Prints a complete Solidity library. Paste the output over test/utils/P256Vectors.sol.
// Pinned deps: @noble/curves@2.4.0, @noble/hashes@2.4.0 (v2 subpaths require the `.js` suffix).
//
// The device digest is bound to the chain and to the Ticket deployment (Tasks 8-10 review, Gap 2),
// so a per-gate signature is no longer a constant this file can hold: every test deployment lands
// Ticket at a different address. Door tests therefore sign at run time with vm.signP256 out of
// Base.t.sol, and this file hands them the keys. What stays pinned is the ONE cross-plan vector,
// whose chainId and Ticket address are fixed by fiat so that packages/shared, sub-plan 03's client
// and this contract can all be checked against the same hex.
import {p256} from '@noble/curves/nist.js';
import {sha256} from '@noble/hashes/sha2.js';

const TOKEN_ID = 1n;
const EVENT_ID = 1001n; // v2: event ids start at 1001 (design D7)
const GATE1_ID = 1n;
const GATE2_ID = 2n;
const NONCE = '11'.repeat(32);
const ISSUED_AT = 1800000000n;

// The pinned cross-plan vector. The Ticket address is the same fictitious one Task 9 pinned the
// EIP-712 offer vector at, so the two shared vectors name one imaginary deployment, not two.
const SHARED_CHAIN_ID = 31337n;
const SHARED_TICKET = 0x7111111111111111111111111111111111111111n;
const SHARED_TOKEN_ID = 7n;
const SHARED_GATE_ID = 3n;
const SHARED_EVENT_ID = 11n;
const SHARED_NONCE = '11'.repeat(32);
const SHARED_ISSUED_AT = 1789862400n;

const DEVICE_PRIV = Uint8Array.from(Array.from({length: 32}, (_, i) => i + 1));
const OTHER_PRIV = Uint8Array.from(Array.from({length: 32}, (_, i) => 200 - i));

const word = (v) => v.toString(16).padStart(64, '0');
const hex = (u8) => Buffer.from(u8).toString('hex');
const priv = (u8) => '0x' + hex(u8);

// sha256(abi.encode(uint256 chainId, address ticket, uint256 tokenId, uint256 gateId,
//                   uint256 eventId, bytes32 nonce, uint64 issuedAt)) -- 7 words, 224 bytes.
function digest({chainId, ticket, tokenId, gateId, eventId, nonce, issuedAt}) {
  const body =
    word(chainId) + word(ticket) + word(tokenId) + word(gateId) + word(eventId) + nonce + word(issuedAt);
  return sha256(Buffer.from(body, 'hex'));
}

function pub(p) {
  const k = p256.getPublicKey(p, false); // 0x04 || X(32) || Y(32)
  return {x: hex(k.slice(1, 33)), y: hex(k.slice(33, 65))};
}

function sign(p, d) {
  const sig = p256.sign(d, p, {lowS: true, prehash: false});
  const {r, s} = p256.Signature.fromBytes(sig); // v2 sign() returns raw 64-byte r||s
  return {r: r.toString(16).padStart(64, '0'), s: s.toString(16).padStart(64, '0')};
}

const dev = pub(DEVICE_PRIV);
const other = pub(OTHER_PRIV);
const shared = digest({
  chainId: SHARED_CHAIN_ID,
  ticket: SHARED_TICKET,
  tokenId: SHARED_TOKEN_ID,
  gateId: SHARED_GATE_ID,
  eventId: SHARED_EVENT_ID,
  nonce: SHARED_NONCE,
  issuedAt: SHARED_ISSUED_AT
});
const sd = sign(DEVICE_PRIV, shared);
const so = sign(OTHER_PRIV, shared);

